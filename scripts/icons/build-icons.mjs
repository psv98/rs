#!/usr/bin/env node
// Builds src/lib/icons/category-icons.generated.ts from the cleaned SVG icons in
// public/icons/categories. Only a strict allowlist of SVG elements/attributes is
// accepted, so a tampered icon file cannot smuggle scripts or event handlers into
// the page.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dir = join(root, "public/icons/categories");
const out = join(root, "src/lib/icons/category-icons.generated.ts");

const ALLOWED_TAGS = new Set(["svg", "g", "path", "circle", "rect", "defs", "mask", "clipPath", "use"]);
const ALLOWED_ATTRS = new Set([
  "xmlns", "viewBox", "fill", "fill-opacity", "fill-rule", "clip-rule", "clip-path", "mask", "d", "cx", "cy", "r",
  "x", "y", "width", "height", "rx", "transform", "id", "href", "maskUnits", "stroke", "stroke-width", "opacity",
]);

function check(svg, file) {
  for (const m of svg.matchAll(/<\/?([a-zA-Z]+)([^>]*)>/g)) {
    const tag = m[1];
    if (!ALLOWED_TAGS.has(tag)) throw new Error(`${file}: element <${tag}> is not allowed`);
    for (const a of m[2].matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
      if (!ALLOWED_ATTRS.has(a[1])) throw new Error(`${file}: attribute ${a[1]} is not allowed`);
      if (a[1] === "href" && !a[2].startsWith("#")) throw new Error(`${file}: external href`);
      if (/javascript:|data:/i.test(a[2])) throw new Error(`${file}: suspicious attribute value`);
    }
  }
}

const icons = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(dir, f), "utf8").trim();
  check(svg, f);
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  icons[f.replace(/\.svg$/, "")] = inner;
}

const body = `// AUTO-GENERATED by scripts/icons/build-icons.mjs — do not edit by hand.
// Source: icons extracted from the IMI infographic SVG (see scripts/icons/README.md).
export const CATEGORY_ICON_VIEWBOX = "0 0 64 64";
export const CATEGORY_ICONS = ${JSON.stringify(icons, null, 2)} as const;
export type CategoryIconId = keyof typeof CATEGORY_ICONS;
export const CATEGORY_ICON_IDS = Object.keys(CATEGORY_ICONS) as CategoryIconId[];
`;
writeFileSync(out, body);
console.log(`Wrote ${Object.keys(icons).length} icons to ${out}`);
